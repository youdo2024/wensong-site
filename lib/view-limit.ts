import { rateLimit, clientIp } from "./ratelimit";

/*
 * 觀看數計數的頻率限制。
 *
 * 三支計數 API（文章、廚師、商品）原本完全沒有限制：任何人寫一行 curl 迴圈
 * 就能把某篇文章的觀看數灌到十萬。這不是安全漏洞——灌了也拿不到任何東西——
 * 但它會毀掉這個數字的可信度，而網站的核心價值就是「上面的數字是真的」。
 *
 * 另一個更實際的理由：每一次請求都是一次同步的 SQLite 寫入，
 * 跑在 Node 那條唯一的執行緒上。沒有上限的話，灌計數等於免費的阻斷服務。
 *
 * 為什麼是 300 次／小時：
 * 一個真人一小時內不可能開 300 個頁面，但辦公室或電信業者的 NAT 後面
 * 可能有好幾十人共用同一個對外 IP，所以不能設太低。
 * 300 這個數字讓正常讀者（含共用 IP）完全碰不到，卻把灌水擋在三位數。
 *
 * 超過上限時回 ok:true 而不是 429：
 * 前端只是「順手回報一下」，它不在乎結果，回錯誤只會在使用者的 console
 * 留下紅字。但 skipped 欄位照實回報，不假裝有算到——
 * 「安靜地不做事又回報成功」正是最難查的那種 bug。
 */
export function viewPingAllowed(headers: Headers, kind: string): boolean {
  return rateLimit(`view:${kind}:${clientIp(headers)}`, 300, 60 * 60 * 1000);
}
